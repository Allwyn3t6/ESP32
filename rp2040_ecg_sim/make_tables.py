#!/usr/bin/env python3
"""Render results/csv/*.csv into Markdown tables (results/summary_tables.md) used in REPORT.md."""
import pandas as pd
a = pd.read_csv("results/csv/aggregate_metrics.csv")
t = pd.read_csv("results/csv/paired_tests.csv")
df = pd.read_csv("results/csv/trial_metrics.csv")
M = [("interval_err_rms_us", "Interval err RMS (µs)", 4), ("interval_err_maxabs_us", "Interval err max (µs)", 3),
     ("acq_sample_loss_rate", "Acq. loss (%)", 3, 100), ("rx_missing_rate", "Rx missing (%)", 3, 100),
     ("device_buffer_overflow_pkts", "Dev. ovf (pkts)", 2), ("receiver_buffer_overflow_pkts", "Rx ovf (pkts)", 2),
     ("lat_median_ms", "Lat p50 (ms)", 2), ("lat_p95_ms", "Lat p95 (ms)", 2), ("lat_p99_ms", "Lat p99 (ms)", 2),
     ("lat_jitter_std_ms", "Lat jitter SD (ms)", 2), ("link_lat_jitter_std_ms", "Link jitter SD (ms)", 4),
     ("rmse_vs_afe_mv", "RMSE vs AFE (mV)", 3), ("rmse_filled_mv", "RMSE filled (mV)", 2), ("snr_db", "SNR (dB)", 2),
     ("r_sensitivity", "R Se", 4), ("r_ppv", "R PPV", 4), ("r_timing_err_rms_ms", "R timing RMS (ms)", 3)]
out = ["# Summary tables (generated by make_tables.py)\n",
       "Values: mean ± SD across 30 trials, [95% CI of the mean]. All values are simulation outputs.\n"]
for cond in a.condition.unique():
    out.append(f"\n## Condition: `{cond}`\n")
    out.append("| Metric | A | B | C |\n|---|---|---|---|")
    g = a[a.condition == cond].set_index("arch")
    for spec in M:
        m, lab, d = spec[:3]
        s = spec[3] if len(spec) > 3 else 1
        cells = []
        for ar in "ABC":
            mu, sd, lo, hi = (g.loc[ar, f"{m}_{k}"] * s for k in ("mean", "std", "ci_lo", "ci_hi"))
            cells.append(f"{mu:.{d}f} ± {sd:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]")
        out.append(f"| {lab} | " + " | ".join(cells) + " |")
out.append("\n## Packet integrity under `packet_loss` (totals over 30 trials)\n")
g = df[df.condition == "packet_loss"].groupby("arch")[["corrupted_packets", "crc_detected", "duplicates", "out_of_order", "packets_lost_detected"]].sum()
out.append(g.to_markdown())
out.append("\n## Paired tests B vs C (Wilcoxon signed-rank, Holm-adjusted over all 336 tests)\n")
bc = t[(t.comparison == "B vs C")].copy()
bc = bc[["condition", "metric", "mean_x", "mean_y", "mean_diff", "diff_ci_lo", "diff_ci_hi", "p_holm", "better"]]
bc.columns = ["condition", "metric", "B mean", "C mean", "B−C", "CI lo", "CI hi", "p (Holm)", "verdict"]
out.append(bc.to_markdown(index=False, floatfmt=".4g"))
out.append("\n## Paired tests A vs B (Holm-adjusted)\n")
ab = t[(t.comparison == "A vs B")][["condition", "metric", "mean_x", "mean_y", "p_holm", "better"]]
ab.columns = ["condition", "metric", "A mean", "B mean", "p (Holm)", "verdict"]
out.append(ab.to_markdown(index=False, floatfmt=".4g"))
s = pd.read_csv("results/csv/sensitivity_aggregate.csv")
out.append("\n## Sensitivity sweeps (10 trials x 120 s each; mean)\n")
for sw, ms in [("cpu_load", ["interval_err_rms_us", "acq_sample_loss_rate", "lat_p99_ms"]),
               ("buffer_size", ["rx_missing_rate", "device_buffer_overflow_pkts", "receiver_buffer_overflow_pkts"]),
               ("stall_duration", ["rx_missing_rate", "lat_p99_ms"]), ("pio_ber", ["rx_missing_rate", "crc_detected"])]:
    for m in ms:
        out.append(f"\n**{sw} → {m}**\n")
        out.append(s[s.sweep == sw].pivot(index="value", columns="arch", values=m + "_mean").to_markdown(floatfmt=".4g"))
open("results/summary_tables.md", "w").write("\n".join(out) + "\n")
print("ok")
